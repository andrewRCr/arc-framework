/** Internal Unicode-scalar validation shared by canonical trust primitives. */

/**
 * Determine whether a string contains only well-formed UTF-16 sequences.
 *
 * @param value - The string to validate
 * @returns Whether every surrogate participates in a valid pair
 */
export function isWellFormedUnicode(value: string): boolean {
  for (let index = 0; index < value.length; index += 1) {
    const codeUnit = value.charCodeAt(index);
    if (codeUnit >= 0xD800 && codeUnit <= 0xDBFF) {
      const next = value.charCodeAt(index + 1);
      if (!(next >= 0xDC00 && next <= 0xDFFF)) return false;
      index += 1;
    } else if (codeUnit >= 0xDC00 && codeUnit <= 0xDFFF) {
      return false;
    }
  }
  return true;
}
