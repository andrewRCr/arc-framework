/** Candidate allocation evidence and accepted whole-batch event receipts. */
import { compareCreatedOwners, CreatedOwnerSchema, BatchCreationReceiptSchema,
  type CreatedOwner, type OwnerIdentity, type WriteInput, type HistoryEntry, type StoreRefusal } from "../../../src/lib/store/index.js";
import { canonicalize } from "../../../src/lib/kernel/canonical/canonical-json.js";
import type { ReferenceContext } from "./context.js";
import { canonicalReference, recordKey, type MemoryEvent } from "./model.js";

/** Intersect backend-fresh allocations with primary creations in the exact proposed namespace. */
export function proposedBirths(found: ReferenceContext, prepared: ReferenceContext,
  writes: readonly WriteInput[], allocations: readonly OwnerIdentity[]): CreatedOwner[] {
  const allocated = new Set(allocations.flatMap(owner => owner.type !== "person" && owner.uid !== undefined
    ? [`${owner.type}:${owner.uid}`] : []));
  const result: CreatedOwner[] = [];
  for (const write of writes) {
    if (write.action !== "put" || !["work-item/meta", "work-item/record", "cohort/document"].includes(write.reference.kind)) continue;
    const reference = canonicalReference(prepared.state, write.reference), owner = reference.owner;
    if (owner.type === "person" || owner.uid === undefined || !allocated.has(`${owner.type}:${owner.uid}`)
      || found.state.records.has(recordKey(reference)) || !prepared.state.records.has(recordKey(reference))) continue;
    result.push(CreatedOwnerSchema.parse({ kind: reference.kind, owner }));
  }
  return result.sort(compareCreatedOwners);
}

/** Publish one complete receipt on every physical event generated by the accepted batch. */
export function retainCreationReceipt(context: ReferenceContext, since: number, batchId: string,
  createdOwners: readonly CreatedOwner[]): void {
  for (const event of context.state.events.slice(since)) {
    event.creationReceipt = { schemaVersion: 1, batchId, createdOwners: structuredClone([...createdOwners]) };
  }
}

/** Every retained physical event of a selected batch must advertise the same whole fact. */
export function checkCreationReceiptGroups(entries: readonly HistoryEntry[], events: readonly MemoryEvent[]): StoreRefusal | undefined {
  const selected = new Set(entries.flatMap(entry => "verb" in entry.provenance && entry.provenance.batchId !== undefined
    ? [entry.provenance.batchId] : []));
  const envelopes = new Map<string, string>();
  for (const event of events) {
    const batchId = "verb" in event.provenance ? event.provenance.batchId : undefined;
    if (batchId === undefined || !selected.has(batchId)) continue;
    const receipt = event.creationReceipt === undefined ? undefined : BatchCreationReceiptSchema.safeParse(event.creationReceipt);
    if (receipt?.success === false || receipt?.data.batchId !== undefined && receipt.data.batchId !== batchId) {
      return corruptBatch(batchId, "A physical event advertises a malformed or batch-mismatched creation receipt.");
    }
    const serialized = receipt === undefined ? "unavailable" : canonicalize(receipt.data);
    if (envelopes.has(batchId) && envelopes.get(batchId) !== serialized) return corruptBatch(batchId,
      "Physical events disagree about the complete batch creation receipt.");
    envelopes.set(batchId, serialized);
  }
  return undefined;
}

function corruptBatch(batchId: string, condition: string): StoreRefusal {
  return { code: "namespace-corrupt", class: "terminal", namespace: `history:batch:${batchId}`, condition,
    remedy: { text: "Restore the complete authentic batch evidence from a known intact source, or explicitly regenerate this development namespace; then retry." } };
}
